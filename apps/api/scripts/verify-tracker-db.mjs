import pg from "pg";

if (!process.env.TRACKER_DATABASE_URL && typeof process.loadEnvFile === "function") {
  try { process.loadEnvFile(".env.local"); } catch {}
}

const connectionString = process.env.TRACKER_DATABASE_URL || process.env.DATABASE_URL_UNPOOLED || process.env.DATABASE_URL;
if (!connectionString) throw new Error("TRACKER_DATABASE_URL, DATABASE_URL_UNPOOLED, or DATABASE_URL is required");

const client = new pg.Client({ connectionString });
const failures = [];
const check = (condition, message) => { if (!condition) failures.push(message); };
let migration;
let parity = {};

await client.connect();
try {
  migration = (await client.query("select migration_name from tracker.schema_migrations order by migration_name desc limit 1")).rows[0];
  check(Boolean(migration), "migration ledger is empty");

  const undocumented = (await client.query("select count(*)::int as count from tracker_read.v_routine_catalog where enabled and purpose like 'Document the purpose%'")).rows[0].count;
  check(undocumented === 0, `${undocumented} enabled routines have autogenerated undocumented purposes`);
  const publicExecute = (await client.query(`select count(*)::int as count
    from information_schema.routine_privileges
    where grantee = 'PUBLIC'
      and privilege_type = 'EXECUTE'
      and specific_schema in ('tracker','tracker_read')`)).rows[0].count;
  check(publicExecute === 0, `${publicExecute} tracker routines remain executable by PUBLIC`);
  const runtimeMaintenance = (await client.query(`select count(*)::int as count
    from pg_proc p
    join pg_namespace n on n.oid=p.pronamespace
    join tracker_read.v_routine_catalog c
      on c.routine_schema=n.nspname
     and c.routine_name=p.proname
     and c.identity_arguments=pg_get_function_identity_arguments(p.oid)
     and c.routine_kind=case when p.prokind='p' then 'procedure' else 'function' end
    where n.nspname='tracker'
      and c.data_operation='maintenance'
      and has_function_privilege('tracker_runtime', p.oid, 'execute')`)).rows[0].count;
  check(runtimeMaintenance === 0, `${runtimeMaintenance} maintenance routines are executable by tracker_runtime`);

  parity = (await client.query(`select
    (select count(*)::int from tracker.research_projects) as projects,
    (select project_count::int from tracker_read.v_workspace_rollups where rollup_key='global') as rollup_projects,
    (select count(*)::int from tracker.parcels) as parcels,
    (select parcel_count::int from tracker_read.v_workspace_rollups where rollup_key='global') as rollup_parcels,
    (select count(*)::int from tracker.discovery_runs) as runs,
    (select discovery_run_count::int from tracker_read.v_workspace_rollups where rollup_key='global') as rollup_runs,
    (select count(*)::int from tracker.discovery_contacts) as contacts,
    (select contact_count::int from tracker_read.v_workspace_rollups where rollup_key='global') as rollup_contacts`)).rows[0];
  for (const [source, rollup] of [["projects", "rollup_projects"], ["parcels", "rollup_parcels"], ["runs", "rollup_runs"], ["contacts", "rollup_contacts"]]) {
    check(parity[source] === parity[rollup], `${source} source/rollup mismatch: ${parity[source]} != ${parity[rollup]}`);
  }

  const researcher = (await client.query("select researcher_id from tracker.discovery_contact_rollups order by total_count desc limit 1")).rows[0]?.researcher_id;
  check(Boolean(researcher), "no researcher contact rollup exists");
  if (researcher) {
    const bounded = await client.query("select * from tracker_read.list_discovery_contacts($1,25,0,null,'created_at','desc')", [researcher]);
    check(bounded.rowCount <= 25, `bounded contact read returned ${bounded.rowCount} rows`);

    const plan = (await client.query(`explain (format json)
      select id, created_at from tracker.discovery_contacts
      where researcher_id=$1 and created_at > $2
      order by created_at desc, id asc limit 25`, [researcher, new Date(0)])).rows[0]["QUERY PLAN"][0];
    const planText = JSON.stringify(plan);
    check(planText.includes("discovery_contacts_researcher_created_id_idx"), "contact page plan does not use the composite tiebreak index");
  }
} finally {
  await client.end();
}

const runtime = new pg.Client({ connectionString });
await runtime.connect();
try {
  await runtime.query("set role tracker_runtime");
  try {
    await runtime.query("select count(*) from tracker.discovery_contacts");
    failures.push("tracker_runtime can read a base tracker table");
  } catch {}
  try {
    await runtime.query("call tracker.reconcile_rollups()");
    failures.push("tracker_runtime can call rollup reconciliation");
  } catch {}
} finally {
  await runtime.end();
}

const report = { ok: failures.length === 0, latestMigration: migration?.migration_name || null, ...parity, failures };
console.log(JSON.stringify(report, null, 2));
if (failures.length) process.exitCode = 1;
